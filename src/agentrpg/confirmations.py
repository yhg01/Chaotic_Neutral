"""Native evidence for explicit peer confirmation, bound to one frozen task.

The model chooses owner decisions and Agent tools. Code preserves the declared
terms and condition and checks committed mail before any completion report.
No acknowledgement or approval is generated by this service on its own.
"""

from uuid import UUID, uuid5

from agentrpg.confirmation_schema import ConfirmationSpec
from agentrpg.director import DirectorError, fingerprint, row, rows, save_message


class ConfirmationError(DirectorError):
    pass


async def initialize(conn, run_id, definitions):
    seen = set()
    for definition in definitions:
        spec = ConfirmationSpec.model_validate(definition)
        key = (spec.owner_id, spec.task_key)
        if key in seen:
            raise ConfirmationError("Duplicate confirmation contract.")
        seen.add(key)
        if spec.activation_event_key:
            from psycopg.types.json import Jsonb

            event = await row(
                conn,
                "SELECT e.* FROM director_clock_bindings b JOIN simulation_clock_events e "
                "ON e.clock_id=b.clock_id JOIN simulation_clock_processes p "
                "ON p.clock_id=b.clock_id AND p.owner_id=%s AND p.role='actor' "
                "WHERE b.run_id=%s AND e.event_key=%s AND e.kind='private_cue' "
                "AND e.recipients @> jsonb_build_array(p.process_id) "
                "AND e.payload @> %s",
                (
                    spec.owner_id,
                    run_id,
                    spec.activation_event_key,
                    Jsonb({"owner_response_required": True}),
                ),
            )
            if not event:
                raise ConfirmationError("The contract needs its declared private Actor cue.")
        await conn.execute(
            "INSERT INTO confirmation_tasks"
            "(id,run_id,task_key,owner_id,peer_owner_id,terms,condition,activation_event_key) "
            "VALUES (%s,%s,%s,%s,%s,%s,%s,%s)",
            (
                uuid5(UUID(str(run_id)), f"confirmation:{spec.owner_id}:{spec.task_key}"),
                run_id,
                spec.task_key,
                spec.owner_id,
                spec.peer_owner_id,
                spec.terms,
                spec.condition,
                spec.activation_event_key,
            ),
        )


async def visible(conn, run_id, owner_id):
    return await rows(
        conn,
        "SELECT t.* FROM confirmation_tasks t WHERE t.run_id=%s AND "
        "(t.owner_id=%s OR (t.peer_owner_id=%s AND t.request_mail_id IS NOT NULL)) "
        "AND (t.activation_event_key IS NULL OR EXISTS (SELECT 1 FROM "
        "director_clock_bindings b JOIN simulation_clock_events e ON e.clock_id=b.clock_id "
        "WHERE b.run_id=t.run_id AND e.event_key=t.activation_event_key "
        "AND e.status='delivered')) ORDER BY t.activation_event_key NULLS FIRST,t.id",
        (run_id, owner_id, owner_id),
    )


async def actor_view(conn, run_id, owner_id):
    tasks = await visible(conn, run_id, owner_id)
    return {"enabled": True, "tasks": tasks} if tasks else {}


def required_actions(view):
    required = {}
    for task in view.confirmations.get("tasks", []):
        if task["owner_id"] == view.owner_id and not task["source_message_id"]:
            required[str(task["id"])] = {"request"}
        elif (
            task["peer_owner_id"] == view.owner_id
            and task["question_message_id"]
            and not task["decision"]
        ):
            required[str(task["id"])] = {"confirm", "decline"}
    return required


def validate_actions(view, output):
    required = required_actions(view)
    actions = output.confirmation_actions
    if len(actions) != len(required) or len({a.task_id for a in actions}) != len(actions):
        raise ConfirmationError(
            "Each current confirmation decision requires exactly one typed owner action."
        )
    for action in actions:
        if action.kind not in required.get(str(action.task_id), set()):
            raise ConfirmationError(
                "This confirmation action is not a current decision of this owner."
            )
    if actions and (output.kind == "wait" or not output.text.strip() or output.mail_requests):
        raise ConfirmationError(
            "Confirmation decisions need owner dialogue; delegate the actual mail to the Agent."
        )
    if view.confirmations.get("enabled") and output.mail_requests:
        raise ConfirmationError(
            "This confirmation profile delegates all contract mail to the personal Agent."
        )


async def apply_actor(conn, run, job, output, message):
    if job["role"] != "actor":
        return
    for action in getattr(output, "confirmation_actions", ()):
        task = await row(
            conn,
            "SELECT * FROM confirmation_tasks WHERE run_id=%s AND id=%s FOR UPDATE",
            (run["id"], action.task_id),
        )
        if not task or message is None:
            raise ConfirmationError("Confirmation decision has no native owner message.")
        if action.kind == "request":
            if task["owner_id"] != job["owner_id"] or task["source_message_id"]:
                raise ConfirmationError("This confirmation request is not new owner work.")
            await conn.execute(
                "UPDATE confirmation_tasks SET source_message_id=%s WHERE id=%s",
                (message["id"], task["id"]),
            )
        else:
            if (
                task["peer_owner_id"] != job["owner_id"]
                or not task["question_message_id"]
                or task["decision"]
            ):
                raise ConfirmationError(
                    "This peer decision is not authorized by the current owner turn."
                )
            await conn.execute(
                "UPDATE confirmation_tasks SET decision=%s,decision_message_id=%s WHERE id=%s",
                (action.kind, message["id"], task["id"]),
            )


async def guard_freeform(conn, run_id, owner_id):
    # Dedicated opt-in contracts use canonical messages, including at final yield.
    if await row(
        conn,
        "SELECT id FROM confirmation_tasks WHERE run_id=%s AND "
        "(owner_id=%s OR peer_owner_id=%s) LIMIT 1",
        (run_id, owner_id, owner_id),
    ):
        raise ConfirmationError(
            "Use ask_confirmation_owner for the decision, or report_confirmation for the actual "
            "outcome. Free-form completion cannot replace a receipt."
        )


async def guard_mail(conn, run_id, sender, recipient):
    if await row(
        conn,
        "SELECT id FROM confirmation_tasks WHERE run_id=%s AND "
        "((owner_id=%s AND peer_owner_id=%s) OR (owner_id=%s AND peer_owner_id=%s)) LIMIT 1",
        (run_id, sender, recipient, recipient, sender),
    ):
        raise ConfirmationError(
            "Use request_confirmation or reply_confirmation so the complete condition and "
            "exact receipt reference are preserved."
        )


def mail_content(task, replying=False):
    if replying:
        verb = "confirms" if task["decision"] == "confirm" else "declines"
        body = (
            f"{task['peer_owner_id']} explicitly {verb} "
            f"the following exact request.\nTerms: {task['terms']}\n"
            f"Condition: {task['condition']}\n"
            f"Owner decision message: {task['decision_message_id']}\n"
            "This is the requested reply; no further acknowledgement of this acknowledgement "
            "is required."
        )
        return (
            task["peer_owner_id"],
            task["owner_id"],
            "Confirmation decision",
            body,
            task["request_mail_id"],
        )
    body = (
        f"{task['owner_id']} requests your explicit confirmation.\nTerms: {task['terms']}\n"
        f"Condition: {task['condition']}\n"
        "This request is PENDING. It is not final until an explicit confirm reply to this exact "
        "message is received. Ask your owner, then use reply_confirmation to send their decision."
    )
    return task["owner_id"], task["peer_owner_id"], "Explicit confirmation requested", body, None


async def mail_context(
    conn, run_id, task_id, sender, recipient, subject, body, in_reply_to, request_id
):
    """Check the internal canonical-mail path against the actual timed Agent call."""
    from agentrpg.clock_runtime import tool_context

    task = await row(
        conn, "SELECT * FROM confirmation_tasks WHERE run_id=%s AND id=%s", (run_id, task_id)
    )
    if not task:
        raise ConfirmationError("Confirmation not found.")
    replying = sender == task["peer_owner_id"]
    expected = mail_content(task, replying)
    if expected != (sender, recipient, subject, body, in_reply_to):
        raise ConfirmationError("Canonical confirmation mail was changed.")
    await tool_context(
        conn,
        run_id,
        sender,
        "reply_confirmation" if replying else "request_confirmation",
        {"task_id": str(task_id)},
        request_id,
    )


async def yield_error(conn, run_id, owner_id, result):
    tasks = await visible(conn, run_id, owner_id)
    if result.text.strip():
        participant = bool(tasks) or await row(
            conn,
            "SELECT id FROM confirmation_tasks WHERE run_id=%s "
            "AND (owner_id=%s OR peer_owner_id=%s) LIMIT 1",
            (run_id, owner_id, owner_id),
        )
        if participant:
            return (
                "Use report_confirmation for an actual outcome, then finish with empty text. "
                "If no request has arrived, there is nothing to report; wait for inbox_received."
            )
    for task in tasks:
        if task["owner_id"] == owner_id:
            if not task["source_message_id"]:
                continue
            if not task["request_mail_id"]:
                return "Send request_confirmation before yielding."
            if task["reply_mail_id"] and not task["owner_report_id"]:
                return (
                    "Read and acknowledge the actual reply with read_mail/acknowledge_mail, "
                    "then report_confirmation."
                )
            if not task["reply_mail_id"] and not (
                result.status == "waiting" and "inbox_received" in result.wait_for
            ):
                return (
                    "The confirmation is pending. Wait for inbox_received; "
                    "do not declare completion."
                )
        elif task["request_mail_id"]:
            if not task["question_message_id"]:
                return "Read the request and use ask_confirmation_owner."
            if not task["decision"] and not (
                result.status == "waiting" and "owner_message" in result.wait_for
            ):
                return "The owner's decision is pending. Wait for owner_message."
            if task["decision"] and not task["reply_mail_id"]:
                return "Send reply_confirmation with the actual recorded owner decision."
            if task["reply_mail_id"] and not task["peer_report_id"]:
                return "Use report_confirmation to report that the actual reply was sent."
    return None


class ConfirmationService:
    def __init__(self, pool):
        self.pool = pool

    async def execute(self, run_id, owner_id, name, task_id=None, request_id=None):
        from agentrpg.clock_runtime import lock_profile, notify, tool_context
        from agentrpg.inbox import InboxService

        async with self.pool.connection() as conn:
            async with conn.transaction():
                if name == "list_confirmations":
                    return {"tasks": await visible(conn, run_id, owner_id)}
                if not await lock_profile(conn, run_id):
                    raise ConfirmationError("Confirmation tools require the elapsed Clock profile.")
                await tool_context(
                    conn, run_id, owner_id, name, {"task_id": str(task_id)}, request_id
                )
                task = await row(
                    conn,
                    "SELECT * FROM confirmation_tasks WHERE run_id=%s AND id=%s AND "
                    "(owner_id=%s OR (peer_owner_id=%s AND request_mail_id IS NOT NULL)) "
                    "FOR UPDATE",
                    (run_id, task_id, owner_id, owner_id),
                )
                if not task:
                    raise ConfirmationError("Confirmation not found in this owner's view.")
                if task["id"] not in {t["id"] for t in await visible(conn, run_id, owner_id)}:
                    raise ConfirmationError("This contract's Clock cue has not been delivered.")
                payload_hash = fingerprint({"tool": name, "task_id": str(task_id)})
                prior = await row(
                    conn,
                    "SELECT * FROM confirmation_operations WHERE run_id=%s "
                    "AND owner_id=%s AND request_id=%s",
                    (run_id, owner_id, request_id),
                )
                if prior:
                    if prior["payload_hash"] != payload_hash:
                        raise ConfirmationError(
                            "The confirmation operation ID has different content."
                        )
                    return prior["result"]

                async def saved(result):
                    from fastapi.encoders import jsonable_encoder
                    from psycopg.types.json import Jsonb

                    result = jsonable_encoder(result)
                    await conn.execute(
                        "INSERT INTO confirmation_operations VALUES (%s,%s,%s,%s,%s)",
                        (run_id, owner_id, request_id, payload_hash, Jsonb(result)),
                    )
                    return result

                requester = task["owner_id"] == owner_id
                if name in {"request_confirmation", "reply_confirmation"}:
                    replying = name == "reply_confirmation"
                    if requester == replying or not task["source_message_id"]:
                        raise ConfirmationError("This owner cannot send that confirmation message.")
                    if replying and not task["decision_message_id"]:
                        raise ConfirmationError(
                            "Ask the owner and wait for their actual decision before replying."
                        )
                    column = "reply_mail_id" if replying else "request_mail_id"
                    if task[column]:
                        return await saved(
                            {
                                "message_id": task[column],
                                "replayed": True,
                                "decision": task["decision"],
                                "status": "reply_sent" if replying else "pending",
                            }
                        )
                    sender, recipient, subject, body, parent = mail_content(task, replying)
                    mail = await InboxService(self.pool).send(
                        run_id,
                        sender,
                        recipient,
                        subject,
                        body,
                        request_id,
                        in_reply_to=parent,
                        connection=conn,
                        confirmation_task_id=task["id"],
                    )
                    await conn.execute(
                        f"UPDATE confirmation_tasks SET {column}=%s WHERE id=%s",
                        (mail["id"], task["id"]),
                    )
                    return await saved(
                        {
                            "message_id": mail["id"],
                            "status": "reply_sent" if replying else "pending",
                            "decision": task["decision"],
                        }
                    )
                if name == "ask_confirmation_owner":
                    if requester:
                        raise ConfirmationError("Only the recipient asks for the peer decision.")
                    if task["question_message_id"]:
                        return await saved(
                            {"message_id": task["question_message_id"], "replayed": True}
                        )
                    content = (
                        f"{task['owner_id']} requests your explicit decision.\n"
                        f"Terms: {task['terms']}\nCondition: {task['condition']}\n"
                        "Please confirm or decline this exact request. "
                        "Your assistant will send your decision as a reply; "
                        "silence is not agreement."
                    )
                    column = "question_message_id"
                elif name == "report_confirmation":
                    column = "owner_report_id" if requester else "peer_report_id"
                    if task[column]:
                        return await saved(
                            {
                                "message_id": task[column],
                                "replayed": True,
                                "decision": task["decision"],
                            }
                        )
                    if not task["reply_mail_id"]:
                        raise ConfirmationError(
                            "No actual peer reply exists. The request remains pending."
                        )
                    if requester:
                        acknowledged = await row(
                            conn,
                            "SELECT 1 FROM inbox_receipts WHERE run_id=%s "
                            "AND owner_id=%s AND message_id=%s",
                            (run_id, owner_id, task["reply_mail_id"]),
                        )
                        if not task["reply_body_read"] or not acknowledged:
                            raise ConfirmationError(
                                "Read and acknowledge the actual peer reply "
                                "before reporting an outcome."
                            )
                        verb = "confirmed" if task["decision"] == "confirm" else "declined"
                        content = (
                            f"{task['peer_owner_id']} has explicitly {verb} your request. "
                            f"Terms: {task['terms']}\nCondition: {task['condition']}\n"
                            f"Actual reply: {task['reply_mail_id']}. "
                            + (
                                "The requested confirmation condition is now satisfied; "
                                "this change is final."
                                if task["decision"] == "confirm"
                                else "The change is not final; the peer declined."
                            )
                        )
                    else:
                        content = (
                            f"I sent your {task['decision']} decision for {task['terms']} "
                            f"as actual reply {task['reply_mail_id']}."
                        )
                else:
                    raise ConfirmationError("Unknown confirmation operation.")
                message = await save_message(
                    conn, run_id, owner_id, "agent", content, uuid5(task["id"], column), 0
                )
                await conn.execute(
                    f"UPDATE confirmation_tasks SET {column}=%s WHERE id=%s",
                    (message["id"], task["id"]),
                )
                await notify(
                    conn,
                    self.pool,
                    run_id,
                    owner_id,
                    "assistant_reply",
                    message["id"],
                    {"message_id": str(message["id"])},
                )
                return await saved(
                    {
                        "message_id": message["id"],
                        "decision": task["decision"],
                        "status": "reported"
                        if name == "report_confirmation"
                        else "awaiting_owner_decision",
                    }
                )
